export const HK_COMBAT_EQUIPMENT_FOLDERS = [
  { key: "root", name: "Оружие и доспехи", parentKey: null, kind: "root" },
  { key: "weapons", name: "01 · Боевое оружие", parentKey: "root", kind: "category", category: "weapon" },
  { key: "shields", name: "02 · Щиты", parentKey: "root", kind: "category", category: "shield" },
  { key: "armor", name: "03 · Доспехи", parentKey: "root", kind: "category", category: "armor" }
];

export function buildCombatEquipmentLibrary() {
  return {
    rootName: "Оружие и доспехи",
    folders: HK_COMBAT_EQUIPMENT_FOLDERS,
    items: HK_COMBAT_EQUIPMENT.map((entry) => ({
      entry,
      folderKey: entry.type === "weapon" ? "weapons" : entry.type === "shield" ? "shields" : "armor"
    }))
  };
}

export function buildCombatEquipmentItemData(entry) {
  return {
    name: entry.name,
    type: entry.type,
    img: entry.type === "weapon" ? "icons/svg/sword.svg" :
      entry.type === "shield" ? "icons/svg/shield.svg" : "icons/svg/armor.svg",
    system: {
      weight: entry.weight,
      quantity: 1,
      damage: entry.damage,
      range: entry.range,
      protection: entry.protection ?? String(entry.damageReduction ?? ""),
      durability: entry.durability,
      quality: entry.quality,
      weaponTypes: entry.weaponTypes,
      grip: entry.grip,
      itemCategory: entry.itemCategory,
      weightLabel: entry.weightLabel,
      cost: entry.cost,
      costLabel: entry.costLabel,
      damageReduction: entry.damageReduction,
      soakBonus: entry.soakBonus,
      soakRerolls: entry.soakRerolls,
      absorption: entry.absorption,
      description: entry.description,
      rules: entry.rules,
      modificationNotes: entry.modificationNotes ?? "",
      sourcePage: entry.sourcePage
    }
  };
}

export function countCombatEquipmentByType(entries = HK_COMBAT_EQUIPMENT) {
  return entries.reduce((totals, entry) => {
    totals[entry.type] = (totals[entry.type] ?? 0) + 1;
    return totals;
  }, { weapon: 0, shield: 0, armor: 0 });
}
